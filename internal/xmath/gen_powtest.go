//go:build ignore

// This program generates testdata/pow.txt, powers with their exact values for the tests of
// Pow. Run it with go generate. It needs bc.
//
// Each line holds x and y as hexadecimal floats and x**y to 40 significant digits. bc
// computes x**y as e(y l(x)) at scale=200 from the exact binary values of x and y.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"log"
	"math"
	"math/big"
	"math/rand/v2"
	"os"
	"os/exec"
	"strings"
)

type pair struct {
	x, y float64
}

func inputs() []pair {
	var ps []pair
	add := func(x, y float64) {
		ps = append(ps, pair{x: x, y: y})
	}

	// Integer bases and exponents, including exact powers.
	for x := 2; x <= 20; x++ {
		for _, y := range []float64{-40, -13, -7, -3, -2, 3, 4, 5, 7, 10, 13, 22, 31, 40} {
			add(float64(x), y)
		}
	}
	for _, x := range []float64{100, 1000, 1e5, 7e7, 123456789} {
		for y := -20.0; y <= 20; y += 3 {
			add(x, y)
		}
	}
	add(100, -13)
	add(1.1, 10)
	add(2, 1023)
	add(2, -1074)
	add(2, 0.5)
	add(3, 1.0/3)
	add(1e308, 1.0000001)

	r := rand.New(rand.NewPCG(1, 2))

	// Negative bases with integer exponents.
	for range 60 {
		x := -math.Ldexp(1+r.Float64(), r.IntN(20)-10)
		add(x, float64(r.IntN(81)-40))
	}

	// Small reals.
	for range 1000 {
		x := 0.05 + r.Float64()*20
		y := (r.Float64()*2 - 1) * 30
		add(x, y)
	}

	// Bases near 1 with large exponents.
	for range 300 {
		d := float64(r.IntN(1<<20)-1<<19) * math.Ldexp(1, -52-r.IntN(4))
		x := 1 + d
		if x == 1 {
			continue
		}
		y := (r.Float64()*1400 - 700) / math.Log(x)
		add(x, y)
	}

	// Any finite base with exponents keeping the result finite.
	for range 1000 {
		x := math.Float64frombits(r.Uint64() &^ (1 << 63))
		if math.IsInf(x, 0) || x != x || x == 1 || x == 0 {
			continue
		}
		y := (r.Float64()*1490 - 745) / math.Log(x)
		add(x, y)
	}

	// Results near overflow and in the subnormal range.
	for range 300 {
		x := math.Ldexp(1+r.Float64(), r.IntN(60)-30)
		if x == 1 {
			continue
		}
		t := 709.78 + (r.Float64()-0.5)*0.01
		if r.IntN(2) == 0 {
			t = -708.4 - r.Float64()*37
		}
		add(x, t/math.Log(x))
	}
	return ps
}

// exact returns a bc expression of the exact value of a finite double.
func exact(f float64) string {
	return new(big.Float).SetFloat64(f).Text('f', 1100)
}

// logExpr returns a bc expression of log(x) for a finite x > 0.
func logExpr(x float64) string {
	frac, exp := math.Frexp(x)
	m := new(big.Float).SetMantExp(new(big.Float).SetFloat64(frac), 53)
	mi, _ := m.Int(nil)
	return fmt.Sprintf("(l(%s)+(%d)*l2)", mi.String(), exp-53)
}

func main() {
	ps := inputs()

	var prog bytes.Buffer
	prog.WriteString(`scale=200
l2=l(2)
l10=l(10)
define t(x) { auto s; s=scale; scale=0; x=x/1; scale=s; return x }
`)
	for _, p := range ps {
		fmt.Fprintf(&prog, "w=%s*%s/l10\n", exact(p.y), logExpr(math.Abs(p.x)))
		prog.WriteString("t(w)\ne((w-t(w))*l10)\n")
	}

	cmd := exec.Command("bc", "-l")
	cmd.Stdin = &prog
	cmd.Env = append(os.Environ(), "BC_LINE_LENGTH=0")
	out, err := cmd.Output()
	if err != nil {
		log.Fatal(err)
	}

	var buf bytes.Buffer
	buf.WriteString("# Generated by gen_powtest.go. DO NOT EDIT.\n")
	s := bufio.NewScanner(bytes.NewReader(out))
	s.Buffer(nil, 1<<20)
	for _, p := range ps {
		if !s.Scan() {
			log.Fatal("bc: short output")
		}
		e := strings.TrimSpace(s.Text())
		if !s.Scan() {
			log.Fatal("bc: short output")
		}
		m := strings.TrimSpace(s.Text())
		v, _, err := big.ParseFloat(m+"e"+e, 10, 800, big.ToNearestEven)
		if err != nil {
			log.Fatal(err)
		}
		if p.x < 0 && math.Mod(p.y, 2) != 0 {
			v.Neg(v)
		}
		fmt.Fprintf(&buf, "%x %x %s\n", p.x, p.y, v.Text('e', 40))
	}
	if err := s.Err(); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("testdata/pow.txt", buf.Bytes(), 0o644); err != nil {
		log.Fatal(err)
	}
}

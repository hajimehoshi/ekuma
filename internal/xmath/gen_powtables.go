// This program generates powtables.go, the tables and constants of Pow. Run it with go
// generate.
//
// The logarithms and powers of two are summed from their series in math/big at 400 bits
// and split into double-doubles.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"math"
	"math/big"
	"os"
)

const prec = 400

func newFloat() *big.Float {
	return new(big.Float).SetPrec(prec)
}

// ln returns the natural logarithm of x > 0 as 2 atanh((x-1)/(x+1)).
func ln(x *big.Float) *big.Float {
	if x.Cmp(big.NewFloat(0.5)) < 0 || x.Cmp(big.NewFloat(2)) > 0 {
		log.Fatalf("ln: %v out of range", x)
	}
	one := newFloat().SetInt64(1)
	s := newFloat().Quo(newFloat().Sub(x, one), newFloat().Add(x, one))
	s2 := newFloat().Mul(s, s)
	sum := newFloat()
	term := newFloat().Set(s)
	eps := newFloat().SetMantExp(one, -prec-8)
	for n := int64(1); ; n += 2 {
		t := newFloat().Quo(term, newFloat().SetInt64(n))
		sum.Add(sum, t)
		if t.Sign() == 0 || newFloat().Abs(t).Cmp(eps) < 0 {
			break
		}
		term.Mul(term, s2)
	}
	return sum.Mul(sum, newFloat().SetInt64(2))
}

// exp returns e**x for |x| <= 1.
func exp(x *big.Float) *big.Float {
	sum := newFloat().SetInt64(1)
	term := newFloat().SetInt64(1)
	eps := newFloat().SetMantExp(big.NewFloat(1), -prec-8)
	for n := int64(1); ; n++ {
		term.Mul(term, x)
		term.Quo(term, newFloat().SetInt64(n))
		sum.Add(sum, term)
		if term.Sign() == 0 || newFloat().Abs(term).Cmp(eps) < 0 {
			break
		}
	}
	return sum
}

// split returns the double nearest to x and the double nearest to the rest.
func split(x *big.Float) (hi, lo float64) {
	hi, _ = x.Float64()
	lo, _ = newFloat().Sub(x, newFloat().SetFloat64(hi)).Float64()
	return hi, lo
}

// splitBits returns x rounded to bits significant bits and the double nearest to the rest.
func splitBits(x *big.Float, bits uint) (hi, lo float64) {
	hi, _ = new(big.Float).SetPrec(bits).SetMode(big.ToNearestEven).Set(x).Float64()
	lo, _ = newFloat().Sub(x, newFloat().SetFloat64(hi)).Float64()
	return hi, lo
}

func main() {
	var buf bytes.Buffer
	buf.WriteString(`// SPDX-License-Identifier: 0BSD
// SPDX-FileCopyrightText: 2026 Hajime Hoshi

// Code generated by gen_powtables.go. DO NOT EDIT.

package xmath

`)

	ln2 := ln(newFloat().SetInt64(2))

	// k ln 2 for |k| < 2**11 is exact in the high part.
	hi, lo := splitBits(ln2, 53-11)
	fmt.Fprintf(&buf, "const (\n")
	fmt.Fprintf(&buf, "\tln2Hi = %v\n", hexFloat(hi))
	fmt.Fprintf(&buf, "\tln2Lo = %v\n", hexFloat(lo))

	// n ln 2 / 128 for |n| < 2**18 is exact in the high part.
	ln2N := newFloat().Quo(ln2, newFloat().SetInt64(expN))
	hi, lo = splitBits(ln2N, 53-18)
	fmt.Fprintf(&buf, "\tln2NHi = %v\n", hexFloat(hi))
	fmt.Fprintf(&buf, "\tln2NLo = %v\n", hexFloat(lo))
	inv, _ := newFloat().Quo(newFloat().SetInt64(1), ln2N).Float64()
	fmt.Fprintf(&buf, "\tinvLn2N = %v\n", hexFloat(inv))
	fmt.Fprintf(&buf, ")\n\n")

	// logTable[i] covers the significands from (i+logFirst)/logScale up to (i+logFirst+1)/logScale.
	fmt.Fprintf(&buf, "// logTable holds, for each interval of significands, a factor c near the reciprocal of\n")
	fmt.Fprintf(&buf, "// its midpoint and -log(c) as a double-double.\n")
	fmt.Fprintf(&buf, "var logTable = [...]struct{ c, logHi, logLo float64 }{\n")
	for i := 0; ; i++ {
		lower := i + logFirst
		if float64(lower)/logScale >= math.Sqrt2 {
			break
		}
		c := 1.0
		// The intervals next to 1 keep c = 1 so that log(x) of x near 1 has no cancellation.
		if lower != logScale-1 && lower != logScale {
			c = logScale / (float64(lower) + 0.5)
		}
		hi, lo := 0.0, 0.0
		if c != 1 {
			hi, lo = split(newFloat().Neg(ln(newFloat().SetFloat64(c))))
		}
		fmt.Fprintf(&buf, "\t{c: %v, logHi: %v, logLo: %v},\n", hexFloat(c), hexFloat(hi), hexFloat(lo))
	}
	fmt.Fprintf(&buf, "}\n\n")

	fmt.Fprintf(&buf, "// exp2Table[j] is 2**(j/%d) as a double-double.\n", expN)
	fmt.Fprintf(&buf, "var exp2Table = [...]struct{ hi, lo float64 }{\n")
	for j := 0; j < expN; j++ {
		z := newFloat().Mul(ln2, newFloat().SetInt64(int64(j)))
		z.Quo(z, newFloat().SetInt64(expN))
		hi, lo := split(exp(z))
		fmt.Fprintf(&buf, "\t{hi: %v, lo: %v},\n", hexFloat(hi), hexFloat(lo))
	}
	fmt.Fprintf(&buf, "}\n")

	src, err := format.Source(buf.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("powtables.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// These must match the constants in pow.go.
const (
	logScale = 256
	logFirst = 181
	expN     = 128
)

func hexFloat(f float64) string {
	if f == 0 {
		return "0"
	}
	return fmt.Sprintf("%x", f)
}

// This program generates persian.go, the leap year corrections of the Persian calendar, from a
// release of ICU4C. Run it with go generate.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"regexp"
	"strings"

	"github.com/hajimehoshi/ekuma/internal/unicode/icu"
)

var nonLeapYears = regexp.MustCompile(`(?s)static int16_t nonLeapYears\[\] = \{([^}]*)\};`)

func main() {
	data, err := icu.ReadFile("icu4c/source/i18n/persncal.cpp")
	if err != nil {
		log.Fatal(err)
	}
	m := nonLeapYears.FindStringSubmatch(string(data))
	if m == nil {
		log.Fatal("persncal.cpp has no nonLeapYears")
	}
	years := strings.FieldsFunc(m[1], func(r rune) bool {
		return r == ',' || r == ' ' || r == '\n' || r == '\t'
	})
	if len(years) == 0 {
		log.Fatal("nonLeapYears is empty")
	}

	var b bytes.Buffer
	b.WriteString("// SPDX-License-Identifier: 0BSD\n// SPDX-FileCopyrightText: 2026 Hajime Hoshi\n\n")
	fmt.Fprintf(&b, "// Code generated by gen_persian.go from ICU4C %s. DO NOT EDIT.\n\npackage calendar\n", icu.Version)
	b.WriteString("\n// persianNonLeapYears are the years of the Persian calendar, in ascending order, that are not\n")
	b.WriteString("// leap years although the 33-year rule makes them leap years. The year after each of them is a\n")
	b.WriteString("// leap year although the rule does not make it one.\n")
	b.WriteString("var persianNonLeapYears = [...]int32{")
	for i, y := range years {
		if i%16 == 0 {
			b.WriteString("\n\t")
		} else {
			b.WriteString(" ")
		}
		b.WriteString(y + ",")
	}
	b.WriteString("\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("persian.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

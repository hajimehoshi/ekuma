// This program generates the tables of package cldr from a CLDR release, and LICENSE, the
// license of the CLDR data that the tables carry. Run it with go generate.
//
// It reads the JSON data of the release (cldr-json, as published on npm) and, for collation,
// the XML data of the release.
package main

import (
	"archive/tar"
	"archive/zip"
	"bytes"
	"compress/gzip"
	"encoding/json"
	"encoding/xml"
	"fmt"
	"go/format"
	"io"
	"log"
	"maps"
	"net/http"
	"os"
	"path"
	"slices"
	"strconv"
	"strings"
)

const (
	jsonVersion = "49.0.0"
	xmlVersion  = "49"
)

const xmlURL = "https://unicode.org/Public/cldr/" + xmlVersion + "/cldr-common-" + xmlVersion + ".zip"

func get(url string) []byte {
	resp, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", url, resp.Status)
	}
	b, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	return b
}

// npmPackage returns the files of the cldr-json package name by their paths in the package.
func npmPackage(name string) map[string][]byte {
	url := "https://registry.npmjs.org/" + name + "/-/" + name + "-" + jsonVersion + ".tgz"
	gz, err := gzip.NewReader(bytes.NewReader(get(url)))
	if err != nil {
		log.Fatal(err)
	}
	tr := tar.NewReader(gz)
	files := map[string][]byte{}
	for {
		h, err := tr.Next()
		if err == io.EOF {
			break
		}
		if err != nil {
			log.Fatal(err)
		}
		if !strings.HasSuffix(h.Name, ".json") && h.Name != "package/LICENSE" {
			continue
		}
		b, err := io.ReadAll(tr)
		if err != nil {
			log.Fatal(err)
		}
		files[strings.TrimPrefix(h.Name, "package/")] = b
	}
	return files
}

// xmlFiles returns the files of the XML release under the directory dir by their base names.
func xmlFiles(dir string) map[string][]byte {
	b := get(xmlURL)
	zr, err := zip.NewReader(bytes.NewReader(b), int64(len(b)))
	if err != nil {
		log.Fatal(err)
	}
	files := map[string][]byte{}
	for _, f := range zr.File {
		if path.Dir(f.Name) != dir || !strings.HasSuffix(f.Name, ".xml") {
			continue
		}
		r, err := f.Open()
		if err != nil {
			log.Fatal(err)
		}
		data, err := io.ReadAll(r)
		r.Close()
		if err != nil {
			log.Fatal(err)
		}
		files[path.Base(f.Name)] = data
	}
	if len(files) == 0 {
		log.Fatalf("%s has no files in %s", xmlURL, dir)
	}
	return files
}

// decode decodes the JSON file name of files and returns the value at the path of keys.
func decode(files map[string][]byte, name string, keys ...string) any {
	b, ok := files[name]
	if !ok {
		log.Fatalf("%s is missing", name)
	}
	var v any
	if err := json.Unmarshal(b, &v); err != nil {
		log.Fatalf("%s: %v", name, err)
	}
	for _, k := range keys {
		m, ok := v.(map[string]any)
		if !ok {
			log.Fatalf("%s: %s is not an object", name, k)
		}
		if v, ok = m[k]; !ok {
			log.Fatalf("%s: %s is missing", name, k)
		}
	}
	return v
}

func object(v any) map[string]any {
	m, ok := v.(map[string]any)
	if !ok {
		log.Fatalf("%v is not an object", v)
	}
	return m
}

func str(v any) string {
	s, ok := v.(string)
	if !ok {
		log.Fatalf("%v is not a string", v)
	}
	return s
}

func strs(v any) []string {
	a, ok := v.([]any)
	if !ok {
		log.Fatalf("%v is not an array", v)
	}
	var out []string
	for _, e := range a {
		out = append(out, str(e))
	}
	return out
}

// file is a generated Go file.
type file struct {
	name string
	b    bytes.Buffer
}

// copyright is the copyright notice of the CLDR data, such as "2001–2026 Unicode, Inc.".
var copyright string

func newFile(name, source string) *file {
	f := &file{name: name}
	fmt.Fprintf(&f.b, "// SPDX-License-Identifier: Unicode-3.0\n// SPDX-FileCopyrightText: %s\n\n", copyright)
	fmt.Fprintf(&f.b, "// Code generated by gen.go from %s. DO NOT EDIT.\n\n", source)
	f.b.WriteString("package cldr\n")
	return f
}

// strings writes the sorted list ss as the Strings variable name.
func (f *file) strings(doc, name string, ss []string) {
	ss = slices.Clone(ss)
	slices.Sort(ss)
	if len(slices.Compact(slices.Clone(ss))) != len(ss) {
		log.Fatalf("%s has duplicates", name)
	}
	fmt.Fprintf(&f.b, "\n// %s %s\nvar %s = %s\n", name, doc, name, stringsLiteral(ss))
}

// mapping writes m as the Map variable name.
func (f *file) mapping(doc, name string, m map[string]string) {
	keys := slices.Sorted(maps.Keys(m))
	var values []string
	for _, k := range keys {
		values = append(values, m[k])
	}
	fmt.Fprintf(&f.b, "\n// %s %s\nvar %s = Map{\n\tkeys: %s,\n\tvalues: %s,\n}\n", name, doc, name, stringsLiteral(keys), stringsLiteral(values))
}

func stringsLiteral(ss []string) string {
	var data strings.Builder
	var ends []string
	for _, s := range ss {
		data.WriteString(s)
		ends = append(ends, strconv.Itoa(data.Len()))
	}
	var b strings.Builder
	b.WriteString("Strings{\n\t\tdata: ")
	// Split the data into lines so that the source stays readable.
	d := data.String()
	if d == "" {
		b.WriteString(`""`)
	}
	for len(d) > 0 {
		n := min(len(d), 96)
		for n < len(d) && !isBoundary(d, n) {
			n++
		}
		if b.Len() > len("Strings{\n\t\tdata: ") {
			b.WriteString(" +\n\t\t\t")
		}
		b.WriteString(strconv.Quote(d[:n]))
		d = d[n:]
	}
	b.WriteString(",\n\t\tends: []uint32{")
	for i, e := range ends {
		if i%16 == 0 {
			b.WriteString("\n\t\t\t")
		} else {
			b.WriteString(" ")
		}
		b.WriteString(e + ",")
	}
	b.WriteString("\n\t\t},\n\t}")
	return b.String()
}

// isBoundary reports whether i is at the start of a UTF-8 sequence in s.
func isBoundary(s string, i int) bool {
	return s[i]&0xc0 != 0x80
}

func (f *file) write() {
	src, err := format.Source(f.b.Bytes())
	if err != nil {
		log.Fatalf("%s: %v", f.name, err)
	}
	if err := os.WriteFile(f.name, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// unicodeLicense returns the copyright notice of the CLDR data and the text of its license,
// the Unicode License v3, from the license text of the release.
func unicodeLicense(text string) (copyright, license string) {
	for l := range strings.Lines(text) {
		if c, ok := strings.CutPrefix(strings.TrimSpace(l), "Copyright © "); ok {
			copyright = c
			break
		}
	}
	// The license of the release also covers the text of UTS #35, which the data does not
	// include. The Unicode License v3 starts at its notice to the user.
	start := strings.Index(text, "NOTICE TO USER:")
	end := strings.Index(text, "SPDX-License-Identifier: Unicode-3.0")
	if copyright == "" || start < 0 || end < start {
		log.Fatal("the license of the release is not the Unicode License v3")
	}
	license = "UNICODE LICENSE V3\n\nCOPYRIGHT AND PERMISSION NOTICE\n\nCopyright © " + copyright + "\n\n" + strings.TrimSpace(text[start:end]) + "\n"
	return copyright, license
}

// keyword holds the BCP 47 data of a Unicode extension or transformed extension key.
type keyword struct {
	// values are the names of the values.
	values []string
	// aliases maps the aliases of values that are valid values to their names, which is how
	// a Unicode locale identifier is canonicalized.
	aliases map[string]string
	// names maps every alias of a value, such as the names in the other CLDR data, to its
	// name.
	names map[string]string
}

// isType reports whether s matches the type production of a Unicode locale identifier.
func isType(s string) bool {
	for t := range strings.SplitSeq(s, "-") {
		if len(t) < 3 || len(t) > 8 {
			return false
		}
		for _, c := range []byte(t) {
			if !('a' <= c && c <= 'z' || '0' <= c && c <= '9') {
				return false
			}
		}
	}
	return true
}

func keywords(files map[string][]byte) map[string]*keyword {
	kws := map[string]*keyword{}
	for name := range files {
		if !strings.HasPrefix(name, "bcp47/") {
			continue
		}
		for _, ext := range object(decode(files, name, "keyword")) {
			for key, v := range object(ext) {
				kw := kws[key]
				if kw == nil {
					kw = &keyword{
						aliases: map[string]string{},
						names:   map[string]string{},
					}
					kws[key] = kw
				}
				for value, d := range object(v) {
					if strings.HasPrefix(value, "_") {
						continue
					}
					kw.values = append(kw.values, value)
					d := object(d)
					if p, ok := d["_preferred"]; ok {
						kw.aliases[value] = str(p)
					}
					a, ok := d["_alias"]
					if !ok {
						continue
					}
					for alias := range strings.FieldsSeq(str(a)) {
						kw.names[alias] = value
						alias = strings.ToLower(alias)
						if alias == value || !isType(alias) {
							continue
						}
						if _, ok := d["_preferred"]; ok {
							alias = value
						}
						if alias != value {
							kw.aliases[alias] = value
						}
					}
				}
			}
		}
	}
	// A preferred value that is an alias of another value resolves to that value.
	for _, kw := range kws {
		for alias, value := range kw.aliases {
			if v, ok := kw.aliases[value]; ok {
				kw.aliases[alias] = v
			}
		}
	}
	return kws
}

func main() {
	core := npmPackage("cldr-core")
	bcp47 := npmPackage("cldr-bcp47")
	numbers := npmPackage("cldr-numbers-full")
	collation := xmlFiles("common/collation")
	jsonSource := "cldr-json " + jsonVersion

	c, license := unicodeLicense(string(core["LICENSE"]))
	copyright = c
	if err := os.WriteFile("LICENSE", []byte(license), 0o644); err != nil {
		log.Fatal(err)
	}
	kws := keywords(bcp47)

	// Available locales.
	locales := map[string]bool{}
	for _, l := range strs(decode(core, "availableLocales.json", "availableLocales", "full")) {
		locales[l] = true
	}
	for _, l := range strs(decode(core, "defaultContent.json", "defaultContent")) {
		locales[l] = true
	}
	f := newFile("availablelocales.go", jsonSource)
	f.strings("are the locales that have data, including the locales whose data is the data of their parents.", "AvailableLocales", slices.Collect(maps.Keys(locales)))
	f.write()

	// Likely subtags.
	likely := map[string]string{}
	for k, v := range object(decode(core, "supplemental/likelySubtags.json", "supplemental", "likelySubtags")) {
		likely[k] = str(v)
	}
	f = newFile("likelysubtags.go", jsonSource)
	f.mapping("maps a language tag to its likely subtags.", "LikelySubtags", likely)
	f.write()

	// Aliases.
	f = newFile("aliases.go", jsonSource)
	aliases := object(decode(core, "supplemental/aliases.json", "supplemental", "metadata", "alias"))
	for _, a := range []struct {
		name, key, doc string
	}{
		{"LanguageAliases", "languageAlias", "maps language aliases, which may include other subtags, to their replacements."},
		{"ScriptAliases", "scriptAlias", "maps script aliases to their replacements."},
		{"TerritoryAliases", "territoryAlias", "maps region aliases to their replacements, separated by spaces."},
		{"VariantAliases", "variantAlias", "maps variant aliases to their replacements."},
		{"SubdivisionAliases", "subdivisionAlias", "maps subdivision aliases to their replacements, separated by spaces."},
	} {
		m := map[string]string{}
		for k, v := range object(aliases[a.key]) {
			m[k] = str(object(v)["_replacement"])
		}
		f.mapping(a.doc, a.name, m)
	}
	f.write()

	// Parent locales.
	f = newFile("parentlocales.go", jsonSource)
	parents := object(decode(core, "supplemental/parentLocales.json", "supplemental", "parentLocales"))
	for _, p := range []struct {
		name, key, doc string
	}{
		{"ParentLocales", "parentLocale", "maps locales to their parents where the parent is not the truncated locale."},
		{"CollationParentLocales", "collations", "maps locales to their parents for collation, where the parent differs from that of ParentLocales."},
	} {
		m := map[string]string{}
		for k, v := range object(parents[p.key]) {
			v := str(v)
			if v == "root" {
				v = "und"
			}
			m[k] = v
		}
		f.mapping(p.doc, p.name, m)
	}
	f.write()

	// Unicode extension values.
	keyAliases := map[string]string{}
	for key, kw := range kws {
		for alias, value := range kw.aliases {
			keyAliases[key+"-"+alias] = value
		}
	}
	f = newFile("bcp47.go", jsonSource)
	f.mapping(`maps a key and an alias of one of its values, joined by "-", to the value.`, "KeywordAliases", keyAliases)
	var collationTypes []string
	for _, v := range kws["co"].values {
		if v != "standard" && v != "search" {
			collationTypes = append(collationTypes, v)
		}
	}
	f.write()

	// Calendar preferences.
	cals := map[string]string{}
	for region, v := range object(decode(core, "supplemental/calendarPreferenceData.json", "supplemental", "calendarPreferenceData")) {
		var names []string
		for _, c := range strs(v) {
			if a, ok := kws["ca"].names[c]; ok {
				c = a
			}
			names = append(names, c)
		}
		cals[region] = strings.Join(names, " ")
	}
	f = newFile("calendarpreferencedata.go", jsonSource)
	f.mapping("maps regions to their calendars, most preferred first and separated by spaces.", "CalendarPreferences", cals)
	f.write()

	// Week data.
	f = newFile("weekdata.go", jsonSource)
	week := object(decode(core, "supplemental/weekData.json", "supplemental", "weekData"))
	for _, w := range []struct {
		name, key, doc string
	}{
		{"FirstDays", "firstDay", "maps regions to the first days of their weeks."},
		{"WeekendStarts", "weekendStart", "maps regions to the first days of their weekends."},
		{"WeekendEnds", "weekendEnd", "maps regions to the last days of their weekends."},
	} {
		m := map[string]string{}
		for k, v := range object(week[w.key]) {
			if strings.Contains(k, "-") {
				// A variant such as "GB-alt-variant".
				continue
			}
			m[k] = str(v)
		}
		f.mapping(w.doc, w.name, m)
	}
	f.write()

	// Time data.
	hours := map[string]string{}
	for k, v := range object(decode(core, "supplemental/timeData.json", "supplemental", "timeData")) {
		hours[strings.ReplaceAll(k, "_", "-")] = str(object(v)["_preferred"])
	}
	f = newFile("timedata.go", jsonSource)
	f.mapping(`maps regions, or languages and regions, to their preferred hour symbols in date patterns ("h", "H", "K" or "k").`, "PreferredHours", hours)
	f.write()

	// Numbering systems.
	digits := map[string]string{}
	for name, v := range object(decode(core, "supplemental/numberingSystems.json", "supplemental", "numberingSystems")) {
		v := object(v)
		if str(v["_type"]) == "numeric" {
			digits[name] = str(v["_digits"])
		}
	}
	defaults := map[string]string{}
	for l := range locales {
		name := "main/" + l + "/numbers.json"
		if _, ok := numbers[name]; !ok {
			continue
		}
		nu := str(decode(numbers, name, "main", l, "numbers", "defaultNumberingSystem"))
		if _, ok := digits[nu]; !ok {
			log.Fatalf("%s: the numbering system %s has no digits", l, nu)
		}
		if nu != "latn" {
			defaults[l] = nu
		}
	}
	f = newFile("numberingsystems.go", jsonSource)
	f.mapping("maps the numbering systems that have digits to their digits from zero to nine.", "NumberingSystemDigits", digits)
	f.mapping(`maps available locales to their default numbering systems, which are "latn" for the locales that it does not have.`, "DefaultNumberingSystems", defaults)
	f.write()

	// Currencies.
	var currencies []string
	for code := range object(decode(numbers, "main/en/currencies.json", "main", "en", "numbers", "currencies")) {
		currencies = append(currencies, code)
	}
	fractions := map[string]string{}
	for code, v := range object(decode(core, "supplemental/currencyData.json", "supplemental", "currencyData", "fractions")) {
		v := object(v)
		field := func(k, def string) string {
			if s, ok := v[k]; ok {
				return str(s)
			}
			return def
		}
		d, r := field("_digits", "2"), field("_rounding", "0")
		fractions[code] = strings.Join([]string{d, r, field("_cashDigits", d), field("_cashRounding", r)}, " ")
	}
	f = newFile("currencydata.go", jsonSource)
	f.strings("are the ISO 4217 codes of the currencies that have names.", "Currencies", currencies)
	f.mapping(`maps currency codes to their digits, rounding increments, cash digits and cash rounding increments, separated by spaces. "DEFAULT" is for the codes that it does not have.`, "CurrencyFractions", fractions)
	f.write()

	// Collations.
	colls := map[string]string{}
	coNames := kws["co"].names
	for name, data := range collation {
		tag := strings.ReplaceAll(strings.TrimSuffix(name, ".xml"), "_", "-")
		if tag == "root" {
			tag = "und"
		}
		var types []string
		d := xml.NewDecoder(bytes.NewReader(data))
		for {
			t, err := d.Token()
			if err == io.EOF {
				break
			}
			if err != nil {
				log.Fatalf("%s: %v", name, err)
			}
			e, ok := t.(xml.StartElement)
			if !ok || e.Name.Local != "collation" {
				continue
			}
			var typ string
			alt := false
			for _, a := range e.Attr {
				switch a.Name.Local {
				case "type":
					typ = a.Value
				case "alt":
					alt = true
				}
			}
			if alt || strings.HasPrefix(typ, "private-") || typ == "standard" || typ == "search" {
				continue
			}
			if a, ok := coNames[typ]; ok {
				typ = a
			}
			if !slices.Contains(collationTypes, typ) {
				// A type that no Unicode locale identifier can name.
				continue
			}
			types = append(types, typ)
		}
		if len(types) > 0 {
			slices.Sort(types)
			colls[tag] = strings.Join(slices.Compact(types), " ")
		}
	}
	f = newFile("collations.go", "the CLDR "+xmlVersion+" XML data")
	f.mapping(`maps locales to the collation types other than "standard" and "search" that they define, sorted and separated by spaces.`, "Collations", colls)
	f.write()

	// Script metadata.
	dirs := map[string]string{}
	for script, v := range object(decode(core, "scriptMetadata.json", "scriptMetadata")) {
		switch str(object(v)["rtl"]) {
		case "YES":
			dirs[script] = "rtl"
		case "NO":
			dirs[script] = "ltr"
		}
	}
	f = newFile("scriptmetadata.go", jsonSource)
	f.mapping(`maps scripts to their directions, "ltr" or "rtl", when they are known.`, "ScriptDirections", dirs)
	f.write()
}

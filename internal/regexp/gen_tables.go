// This program generates regexp property and case folding tables.
package main

import (
	"bufio"
	"bytes"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"slices"
	"sort"
	"strconv"
	"strings"
	"unicode"

	"github.com/hajimehoshi/ekuma/internal/unicode/icu"
)

// Code-point properties use the same UCD as Go and the pinned Test262 fixtures.
const version = "17.0.0"

const base = "https://www.unicode.org/Public/" + version + "/"

func fetch(path string) []string {
	resp, err := http.Get(base + path)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", path, resp.Status)
	}
	b, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	return lines(b)
}

func icuLines(file string) []string {
	b, err := icu.ReadFile("icu4c/source/data/unidata/" + file)
	if err != nil {
		log.Fatal(err)
	}
	return lines(b)
}

func lines(b []byte) []string {
	var lines []string
	sc := bufio.NewScanner(bytes.NewReader(b))
	for sc.Scan() {
		l := sc.Text()
		if i := strings.IndexByte(l, '#'); i >= 0 {
			l = l[:i]
		}
		if l = strings.TrimSpace(l); l != "" {
			lines = append(lines, l)
		}
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
	return lines
}

func fields(l string) []string {
	f := strings.Split(l, ";")
	for i := range f {
		f[i] = strings.TrimSpace(f[i])
	}
	return f
}

func codeRange(s string) (rune, rune) {
	lo, hi, ok := strings.Cut(s, "..")
	if !ok {
		hi = lo
	}
	a, err := strconv.ParseUint(lo, 16, 32)
	if err != nil {
		log.Fatal(err)
	}
	b, err := strconv.ParseUint(hi, 16, 32)
	if err != nil {
		log.Fatal(err)
	}
	return rune(a), rune(b)
}

type set map[rune]bool

func (s set) ranges() []rune {
	cs := make([]rune, 0, len(s))
	for c := range s {
		cs = append(cs, c)
	}
	slices.Sort(cs)
	var out []rune
	for _, c := range cs {
		if n := len(out); n > 0 && out[n-1]+1 == c {
			out[n-1] = c
			continue
		}
		out = append(out, c, c)
	}
	return out
}

// properties reads the binary properties of a file whose lines are "range ; Property".
func properties(path string, want map[string]bool, out map[string]set) {
	for _, l := range fetch(path) {
		f := fields(l)
		if len(f) < 2 || !want[f[1]] {
			continue
		}
		lo, hi := codeRange(f[0])
		s := out[f[1]]
		if s == nil {
			s = set{}
			out[f[1]] = s
		}
		for c := lo; c <= hi; c++ {
			s[c] = true
		}
	}
}

func main() {
	var b bytes.Buffer
	b.WriteString("// SPDX-License-Identifier: 0BSD\n// SPDX-FileCopyrightText: 2026 Hajime Hoshi\n\n")
	b.WriteString("// Code generated by gen_tables.go from UCD " + version + " (code-point properties) and ICU " + icu.Version + " (folding and emoji sequences). DO NOT EDIT.\n\n")
	b.WriteString("package regexp\n\n")
	fmt.Fprintf(&b, "const unicodeVersion = %q\n\n", version)

	// Aliases of the values of General_Category and Script.
	gc := map[string]string{}
	sc := map[string]string{}
	for _, l := range fetch("ucd/PropertyValueAliases.txt") {
		f := fields(l)
		switch f[0] {
		case "gc":
			for _, a := range f[1:] {
				gc[a] = f[1]
			}
		case "sc":
			for _, a := range f[1:] {
				sc[a] = f[2]
			}
		}
	}
	writeMap(&b, "gcAliases", "maps every name of a General_Category value to its short name.", gc)
	// The unicode package names some scripts differently from their long names.
	for a, long := range sc {
		if _, ok := unicode.Scripts[long]; !ok {
			log.Printf("script %s (%s) is not in the unicode package", long, a)
		}
	}
	writeMap(&b, "scriptAliases", "maps every name of a Script value to its long name.", sc)

	derived := map[string]set{}
	properties("ucd/DerivedCoreProperties.txt", map[string]bool{
		"Alphabetic": true, "Lowercase": true, "Uppercase": true, "Math": true,
		"Cased": true, "Case_Ignorable": true,
		"Changes_When_Lowercased": true, "Changes_When_Uppercased": true, "Changes_When_Titlecased": true,
		"Changes_When_Casefolded": true, "Changes_When_Casemapped": true,
		"ID_Start": true, "ID_Continue": true, "XID_Start": true, "XID_Continue": true,
		"Default_Ignorable_Code_Point": true, "Grapheme_Extend": true, "Grapheme_Base": true,
	}, derived)
	properties("ucd/DerivedNormalizationProps.txt", map[string]bool{"Changes_When_NFKC_Casefolded": true}, derived)
	properties("ucd/extracted/DerivedBinaryProperties.txt", map[string]bool{"Bidi_Mirrored": true}, derived)
	properties("ucd/emoji/emoji-data.txt", map[string]bool{
		"Emoji": true, "Emoji_Presentation": true, "Emoji_Modifier": true, "Emoji_Modifier_Base": true,
		"Emoji_Component": true, "Extended_Pictographic": true,
	}, derived)
	writeSets(&b, "derivedProperties", "holds the binary properties that the unicode package does not have.", derived)

	// Script_Extensions: the characters whose extensions differ from their script.
	scx := map[string]set{}
	for _, l := range fetch("ucd/ScriptExtensions.txt") {
		f := fields(l)
		lo, hi := codeRange(f[0])
		for _, short := range strings.Fields(f[1]) {
			long := sc[short]
			if long == "" {
				log.Fatalf("unknown script %s", short)
			}
			s := scx[long]
			if s == nil {
				s = set{}
				scx[long] = s
			}
			for c := lo; c <= hi; c++ {
				s[c] = true
			}
		}
	}
	// The characters that are listed, so that their Script value does not count.
	listed := set{}
	for _, l := range fetch("ucd/ScriptExtensions.txt") {
		lo, hi := codeRange(fields(l)[0])
		for c := lo; c <= hi; c++ {
			listed[c] = true
		}
	}
	writeSets(&b, "scriptExtensions", "holds, for each script, the characters that list it in ScriptExtensions.txt.", scx)
	fmt.Fprintf(&b, "// scriptExtensionsListed holds the characters that ScriptExtensions.txt lists.\nvar scriptExtensionsListed = charSet{%s}\n\n", runes(listed.ranges()))

	// C and S rows map single characters to their default simple folds.
	b.WriteString("var simpleFoldPairs = [...][2]rune{\n")
	for _, l := range icuLines("CaseFolding.txt") {
		f := fields(l)
		if f[1] == "C" || f[1] == "S" {
			from, _ := codeRange(f[0])
			to, _ := codeRange(f[2])
			fmt.Fprintf(&b, "{0x%X, 0x%X},\n", from, to)
		}
	}
	b.WriteString("}\n\n")

	// Properties of strings.
	strs := map[string][]string{}
	for _, file := range []string{"emoji-sequences.txt", "emoji-zwj-sequences.txt"} {
		for _, l := range icuLines(file) {
			f := fields(l)
			if len(f) < 2 {
				continue
			}
			prop := f[1]
			if strings.Contains(f[0], "..") {
				lo, hi := codeRange(f[0])
				for c := lo; c <= hi; c++ {
					strs[prop] = append(strs[prop], string(c))
				}
				continue
			}
			var s []rune
			for _, h := range strings.Fields(f[0]) {
				v, err := strconv.ParseUint(h, 16, 32)
				if err != nil {
					log.Fatal(err)
				}
				s = append(s, rune(v))
			}
			strs[prop] = append(strs[prop], string(s))
		}
	}
	names := make([]string, 0, len(strs))
	for k := range strs {
		names = append(names, k)
	}
	sort.Strings(names)
	b.WriteString("// stringProperties holds the properties of strings, each string being one sequence.\nvar stringProperties = map[string][]string{\n")
	for _, k := range names {
		fmt.Fprintf(&b, "%q: {\n", k)
		for _, s := range strs[k] {
			fmt.Fprintf(&b, "%q,\n", s)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("tables.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func runes(rs []rune) string {
	var sb strings.Builder
	for i, r := range rs {
		if i > 0 {
			sb.WriteString(", ")
		}
		fmt.Fprintf(&sb, "0x%X", r)
	}
	return sb.String()
}

func writeMap(b *bytes.Buffer, name, doc string, m map[string]string) {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	fmt.Fprintf(b, "// %s %s\nvar %s = map[string]string{\n", name, doc, name)
	for _, k := range keys {
		fmt.Fprintf(b, "%q: %q,\n", k, m[k])
	}
	b.WriteString("}\n\n")
}

func writeSets(b *bytes.Buffer, name, doc string, m map[string]set) {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	// Each set is a variable of its own, which the linker initializes statically, and the map
	// only refers to them.
	fmt.Fprintf(b, "// %s %s\nvar %s = map[string]charSet{\n", name, doc, name)
	for _, k := range keys {
		fmt.Fprintf(b, "%q: %s,\n", k, setVar(name, k))
	}
	b.WriteString("}\n\n")
	for _, k := range keys {
		fmt.Fprintf(b, "var %s = charSet{%s}\n\n", setVar(name, k), runes(m[k].ranges()))
	}
}

// setVar returns the name of the variable that holds the set k of the table name.
func setVar(name, k string) string {
	return name + strings.ReplaceAll(k, "_", "")
}

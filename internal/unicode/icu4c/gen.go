// This program generates the tables of package icu4c from a release of ICU4C, and LICENSE,
// the license of that data. Run it with go generate.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"regexp"
	"strings"
)

const release = "release-79.1"

// sources are the files of the release that the program reads, with their SHA-256 checksums.
var sources = map[string]string{
	"LICENSE":                        "e09827667e0bb3c808b2a463548ba814a5e6249b67353234d70c8dfc2bcc417d",
	"icu4c/source/i18n/persncal.cpp": "31e7e93bb7dc1e4436c58ffd44fd1ed2686ceb79228b8d989f6573ec15ed5f45",
}

// get returns the file path of the release, after checking its checksum.
func get(path string) string {
	url := "https://raw.githubusercontent.com/unicode-org/icu/" + release + "/" + path
	resp, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", url, resp.Status)
	}
	b, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	sum := sha256.Sum256(b)
	if hex.EncodeToString(sum[:]) != sources[path] {
		log.Fatalf("%s: unexpected SHA-256 %x", url, sum)
	}
	return string(b)
}

// unicodeLicense returns the Unicode License v3 at the start of the license of ICU, without the
// licenses of the third-party software that follow it.
func unicodeLicense(license string) string {
	const end = "SPDX-License-Identifier: Unicode-3.0\n"
	if !strings.HasPrefix(license, "UNICODE LICENSE V3") {
		log.Fatal("the license of ICU does not start with the Unicode License v3")
	}
	i := strings.Index(license, end)
	if i < 0 {
		log.Fatal("the license of ICU has no end of the Unicode License v3")
	}
	return license[:i+len(end)]
}

// copyright returns the copyright line of the license.
func copyright(license string) string {
	for line := range strings.SplitSeq(license, "\n") {
		if s, ok := strings.CutPrefix(strings.TrimSpace(line), "Copyright © "); ok {
			return s
		}
	}
	log.Fatal("no copyright in the license of ICU")
	return ""
}

var nonLeapYears = regexp.MustCompile(`(?s)static int16_t nonLeapYears\[\] = \{([^}]*)\};`)

func main() {
	license := unicodeLicense(get("LICENSE"))
	m := nonLeapYears.FindStringSubmatch(get("icu4c/source/i18n/persncal.cpp"))
	if m == nil {
		log.Fatal("persncal.cpp has no nonLeapYears")
	}
	years := strings.FieldsFunc(m[1], func(r rune) bool {
		return r == ',' || r == ' ' || r == '\n' || r == '\t'
	})
	if len(years) == 0 {
		log.Fatal("nonLeapYears is empty")
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, "// SPDX-License-Identifier: Unicode-3.0\n// SPDX-FileCopyrightText: %s\n\n", copyright(license))
	fmt.Fprintf(&b, "// Code generated by gen.go from ICU4C %s. DO NOT EDIT.\n\npackage icu4c\n", strings.TrimPrefix(release, "release-"))
	b.WriteString("\n// PersianNonLeapYears are the years of the Persian calendar, in ascending order, that are not\n")
	b.WriteString("// leap years although the 33-year rule makes them leap years. The year after each of them is a\n")
	b.WriteString("// leap year although the rule does not make it one.\n")
	b.WriteString("var PersianNonLeapYears = [...]int32{")
	for i, y := range years {
		if i%16 == 0 {
			b.WriteString("\n\t")
		} else {
			b.WriteString(" ")
		}
		b.WriteString(y + ",")
	}
	b.WriteString("\n}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("persian.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("LICENSE", []byte(license), 0o644); err != nil {
		log.Fatal(err)
	}
}

//go:build ignore

// This program generates the default case mappings and final sigma properties.
package main

import (
	"bytes"
	"fmt"
	"go/format"
	"iter"
	"log"
	"maps"
	"os"
	"slices"
	"strconv"
	"strings"
	"unicode/utf8"

	"github.com/hajimehoshi/ekuma/internal/unicode/icu"
)

func records(name string) iter.Seq[[]string] {
	data, err := icu.ReadFile("icu4c/source/data/unidata/" + name)
	if err != nil {
		log.Fatal(err)
	}
	return func(yield func([]string) bool) {
		for line := range strings.Lines(string(data)) {
			line, _, _ = strings.Cut(line, "#")
			line = strings.TrimSpace(line)
			if line == "" {
				continue
			}
			fields := strings.Split(line, ";")
			for i := range fields {
				fields[i] = strings.TrimSpace(fields[i])
			}
			if !yield(fields) {
				return
			}
		}
	}
}

func codepoint(hex string) rune {
	n, err := strconv.ParseUint(hex, 16, 32)
	if err != nil || n > utf8.MaxRune {
		log.Fatalf("invalid code point %q", hex)
	}
	return rune(n)
}

type mappings map[rune]string

func (m mappings) set(r rune, field string) {
	var b strings.Builder
	for _, hex := range strings.Fields(field) {
		b.WriteRune(codepoint(hex))
	}
	if b.Len() == 0 || b.String() == string(r) {
		delete(m, r)
		return
	}
	m[r] = b.String()
}

func writeMappings(b *bytes.Buffer, name string, m mappings) {
	fmt.Fprintf(b, "var %s = caseTable{\n", name)
	keys := slices.Sorted(maps.Keys(m))
	for i := 0; i < len(keys); {
		lo := keys[i]
		to, n := utf8.DecodeRuneInString(m[lo])
		if n < len(m[lo]) {
			fmt.Fprintf(b, "{\nlo: %#x,\nhi: %#x,\nstride: 1,\nexpansion: %s,\n},\n", lo, lo, strconv.Quote(m[lo]))
			i++
			continue
		}
		// Adjacent mappings with the same delta often alternate upper and lower case.
		delta := to - lo
		hi, stride := lo, rune(1)
		i++
		for i < len(keys) {
			r := keys[i]
			step := r - hi
			if step > 2 || hi != lo && step != stride || m[r] != string(r+delta) {
				break
			}
			hi, stride = r, step
			i++
		}
		fmt.Fprintf(b, "{\nlo: %#x,\nhi: %#x,\nstride: %d,\ndelta: %d,\n},\n", lo, hi, stride, delta)
	}
	fmt.Fprintln(b, "}")
}

func readProperties() map[string][]rune {
	// Successive boundaries delimit half-open ranges for each property.
	properties := map[string][]rune{"Cased": nil, "Case_Ignorable": nil}
	for f := range records("DerivedCoreProperties.txt") {
		bounds, ok := properties[f[1]]
		if !ok {
			continue
		}
		first, last, ranged := strings.Cut(f[0], "..")
		lo := codepoint(first)
		hi := lo
		if ranged {
			hi = codepoint(last)
		}
		if len(bounds) > 0 && bounds[len(bounds)-1] == lo {
			bounds[len(bounds)-1] = hi + 1
		} else {
			bounds = append(bounds, lo, hi+1)
		}
		properties[f[1]] = bounds
	}
	return properties
}

func writeBounds(b *bytes.Buffer, name string, bounds []rune) {
	fmt.Fprintf(b, "var %s = []rune{\n", name)
	for row := range slices.Chunk(bounds, 10) {
		for _, r := range row {
			fmt.Fprintf(b, "%#x,", r)
		}
		fmt.Fprintln(b)
	}
	fmt.Fprintln(b, "}")
}

func main() {
	upper, lower := mappings{}, mappings{}
	for f := range records("UnicodeData.txt") {
		r := codepoint(f[0])
		if f[12] != "" {
			upper.set(r, f[12])
		}
		if f[13] != "" {
			lower.set(r, f[13])
		}
	}
	for f := range records("SpecialCasing.txt") {
		// Locale tailoring and the Final_Sigma context are handled by their callers.
		if f[4] == "" {
			r := codepoint(f[0])
			upper.set(r, f[3])
			lower.set(r, f[1])
		}
	}
	var b bytes.Buffer
	fmt.Fprintln(&b, "// SPDX-License-Identifier: Unicode-3.0")
	fmt.Fprintln(&b, "// SPDX-FileCopyrightText: 1991-2026 Unicode, Inc.")
	fmt.Fprintf(&b, "\n// Code generated by gen_case.go from ICU %s. DO NOT EDIT.\n\npackage xstrings\n\n", icu.Version)
	writeMappings(&b, "upperCaseRanges", upper)
	writeMappings(&b, "lowerCaseRanges", lower)
	properties := readProperties()
	writeBounds(&b, "casedBounds", properties["Cased"])
	writeBounds(&b, "caseIgnorableBounds", properties["Case_Ignorable"])
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("casetables.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

// This program generates windowszones_windows.go, the IANA time zones of the time zones of
// Windows, from windowsZones.xml of CLDR 49: for each ID of a time zone of Windows, the zone
// that CLDR gives the territory 001. Run it with go generate.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/xml"
	"fmt"
	"go/format"
	"io"
	"log"
	"maps"
	"net/http"
	"os"
	"slices"
	"strings"
)

const release = "release-49"

const url = "https://raw.githubusercontent.com/unicode-org/cldr/" + release + "/common/supplemental/windowsZones.xml"

// sum is the SHA-256 checksum of the file at url.
const sum = "5f902f94106a396cb7774f0b0e1ca4dfecb686494045350c0b4935d378e3913b"

func main() {
	resp, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", url, resp.Status)
	}
	b, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	if s := sha256.Sum256(b); hex.EncodeToString(s[:]) != sum {
		log.Fatalf("%s: unexpected SHA-256 %x", url, s)
	}

	var doc struct {
		MapZones []struct {
			Other     string `xml:"other,attr"`
			Territory string `xml:"territory,attr"`
			Type      string `xml:"type,attr"`
		} `xml:"windowsZones>mapTimezones>mapZone"`
	}
	if err := xml.Unmarshal(b, &doc); err != nil {
		log.Fatal(err)
	}
	zones := map[string]string{}
	for _, m := range doc.MapZones {
		if m.Territory != "001" {
			continue
		}
		// type lists the zones of the territory; the first is the one for the territory.
		zone, _, _ := strings.Cut(m.Type, " ")
		zones[m.Other] = zone
	}
	if len(zones) == 0 {
		log.Fatal("windowsZones.xml has no zones for 001")
	}

	var out bytes.Buffer
	out.WriteString("// SPDX-License-Identifier: 0BSD\n// SPDX-FileCopyrightText: 2026 Hajime Hoshi\n\n")
	out.WriteString("// Code generated by gen_windowszones.go from windowsZones.xml of CLDR 49 (" + release + "). DO NOT EDIT.\n\n")
	out.WriteString("package datetime\n\n")
	names := slices.Sorted(maps.Keys(zones))
	out.WriteString("// windowsZoneIDs are the IDs of the time zones of Windows, sorted.\nvar windowsZoneIDs = []string{\n")
	for _, n := range names {
		fmt.Fprintf(&out, "\t%q,\n", n)
	}
	out.WriteString("}\n\n// windowsIANAZones are the IANA time zones of windowsZoneIDs.\nvar windowsIANAZones = []string{\n")
	for _, n := range names {
		fmt.Fprintf(&out, "\t%q,\n", zones[n])
	}
	out.WriteString("}\n")
	src, err := format.Source(out.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("windowszones_windows.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
}

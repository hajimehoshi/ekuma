// This program generates zonelinks.go, the links of the IANA time zone database and the
// zones they resolve to, and zonetab.go, the zones with the countries that zone.tab gives
// them. Run it with go generate.
//
// The links resolve as in a database built with PACKRATDATA=backzone PACKRATLIST=zone.tab,
// which keeps each country's zones apart, except that every identifier in zone.tab is a zone,
// as ECMA-402 requires. A link resolves through the link that its "#= TARGET1" comment names,
// as if the data could link to links.
package main

import (
	"archive/tar"
	"bytes"
	"compress/gzip"
	"fmt"
	"go/format"
	"io"
	"log"
	"maps"
	"net/http"
	"os"
	"slices"
	"strings"
)

const version = "2026f"

const url = "https://data.iana.org/time-zones/releases/tzdata" + version + ".tar.gz"

// mainFiles are the files of the main data, whose links backzone overrides.
var mainFiles = []string{
	"africa",
	"antarctica",
	"asia",
	"australasia",
	"europe",
	"northamerica",
	"southamerica",
	"etcetera",
	"factory",
	"backward",
}

func fetch() map[string][]byte {
	resp, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", url, resp.Status)
	}
	gz, err := gzip.NewReader(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	tr := tar.NewReader(gz)
	files := map[string][]byte{}
	for {
		h, err := tr.Next()
		if err == io.EOF {
			break
		}
		if err != nil {
			log.Fatal(err)
		}
		b, err := io.ReadAll(tr)
		if err != nil {
			log.Fatal(err)
		}
		files[h.Name] = b
	}
	return files
}

// entry is a Zone or Link line of the data.
type entry struct {
	link bool
	// name is the name of the zone or the link.
	name string
	// target is the target of a link.
	target string
	// vanguard is the target of a link that the data would have if it could link to links.
	vanguard string
}

func entries(files map[string][]byte, file string) []entry {
	data, ok := files[file]
	if !ok {
		log.Fatalf("%s is not in %s", file, url)
	}
	var es []entry
	for l := range strings.Lines(string(data)) {
		// Links that apply only to a build with PACKRATLIST=zone.tab are commented out.
		l = strings.TrimPrefix(l, "#PACKRATLIST zone.tab ")
		code, comment, _ := strings.Cut(l, "#")
		f := strings.Fields(code)
		if len(f) == 0 {
			continue
		}
		switch f[0] {
		case "Zone":
			es = append(es, entry{
				name: f[1],
			})
		case "Link":
			if len(f) != 3 {
				log.Fatalf("%s: malformed link: %s", file, l)
			}
			e := entry{
				link:   true,
				name:   f[2],
				target: f[1],
			}
			if v, ok := strings.CutPrefix(comment, "="); ok {
				e.vanguard = strings.TrimSpace(v)
			}
			es = append(es, e)
		}
	}
	return es
}

func main() {
	files := fetch()

	zoneTab := map[string]bool{}
	countries := map[string]string{}
	for l := range strings.Lines(string(files["zone.tab"])) {
		if strings.HasPrefix(l, "#") {
			continue
		}
		f := strings.Split(strings.TrimSuffix(l, "\n"), "\t")
		if len(f) < 3 {
			log.Fatalf("zone.tab: malformed line: %s", l)
		}
		zoneTab[f[2]] = true
		countries[f[2]] = f[0]
	}
	if len(zoneTab) == 0 {
		log.Fatal("zone.tab has no zones")
	}

	zones := maps.Clone(zoneTab)
	links := map[string]string{}
	for _, file := range mainFiles {
		for _, e := range entries(files, file) {
			if !e.link {
				zones[e.name] = true
				continue
			}
			links[e.name] = e.target
			if e.vanguard != "" {
				links[e.name] = e.vanguard
			}
		}
	}

	// backzone lists the links that each of its zones overrides after the zone. A build with
	// PACKRATLIST=zone.tab takes only the zones in zone.tab from backzone.
	backZones := map[string]bool{}
	for _, e := range entries(files, "backzone") {
		if !e.link {
			backZones[e.name] = true
			continue
		}
		if !backZones[e.target] {
			log.Fatalf("backzone: the link %s does not follow its target %s", e.name, e.target)
		}
		if zoneTab[e.target] {
			links[e.name] = e.target
		}
	}

	resolved := map[string]string{}
	names := map[string]string{}
	for name := range zones {
		names[strings.ToLower(name)] = name
	}
	for name := range links {
		if zones[name] {
			continue
		}
		if other, ok := names[strings.ToLower(name)]; ok {
			log.Fatalf("%s and %s differ only in case", name, other)
		}
		names[strings.ToLower(name)] = name
		target := name
		for range len(links) + 1 {
			if zones[target] {
				break
			}
			t, ok := links[target]
			if !ok {
				log.Fatalf("%s links to %s, which is neither a zone nor a link", name, target)
			}
			target = t
		}
		if !zones[target] {
			log.Fatalf("the links from %s form a cycle", name)
		}
		resolved[name] = target
	}

	var b bytes.Buffer
	b.WriteString("// SPDX-License-Identifier: 0BSD\n// SPDX-FileCopyrightText: 2026 Hajime Hoshi\n\n")
	b.WriteString("// Code generated by gen_zonelinks.go from the IANA time zone database " + version + ". DO NOT EDIT.\n\n")
	b.WriteString("package datetime\n\n")
	b.WriteString("// zoneLinks maps the links of the IANA time zone database to the zones they resolve to, with\n")
	b.WriteString("// every identifier in zone.tab taken as a zone.\n")
	b.WriteString("var zoneLinks = map[string]string{\n")
	for _, name := range slices.Sorted(maps.Keys(resolved)) {
		fmt.Fprintf(&b, "\t%q: %q,\n", name, resolved[name])
	}
	b.WriteString("}\n")

	write("zonelinks.go", b.Bytes())

	b.Reset()
	b.WriteString("// SPDX-License-Identifier: 0BSD\n// SPDX-FileCopyrightText: 2026 Hajime Hoshi\n\n")
	b.WriteString("// Code generated by gen_zonelinks.go from the IANA time zone database " + version + ". DO NOT EDIT.\n\n")
	b.WriteString("package datetime\n\n")
	b.WriteString("// zoneTab lists the zones of the IANA time zone database other than Factory by their\n")
	b.WriteString("// primary identifiers, sorted, with the countries that zone.tab gives them.\n")
	b.WriteString("var zoneTab = []zoneTabEntry{\n")
	primaries := map[string]bool{}
	for name := range zones {
		if name == "Factory" {
			continue
		}
		primaries[primaryOfUTC(name)] = true
	}
	for _, name := range slices.Sorted(maps.Keys(primaries)) {
		fmt.Fprintf(&b, "\t{zone: %q, country: %q},\n", name, countries[name])
	}
	b.WriteString("}\n")
	write("zonetab.go", b.Bytes())
}

// primaryOfUTC returns the primary identifier for the identifiers that ECMA-262 treats as UTC,
// as the function of the same name in package datetime does.
func primaryOfUTC(id string) string {
	switch id {
	case "Etc/UTC", "Etc/GMT", "GMT":
		return "UTC"
	}
	return id
}

func write(name string, b []byte) {
	src, err := format.Source(b)
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(name, src, 0o644); err != nil {
		log.Fatal(err)
	}
}
